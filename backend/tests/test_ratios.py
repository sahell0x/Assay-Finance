class TestTrends:
    # Apple net sales, newest first, from the FY2024 and FY2022 filings.
    REVENUE = [
        ("FY2024", 391_035.0),
        ("FY2023", 383_285.0),
        ("FY2022", 394_328.0),
        ("FY2021", 365_817.0),
        ("FY2020", 274_515.0),
    ]

    def test_yoy(self):
        # (391,035 - 383,285) / 383,285 = 0.020220
        assert t.yoy(self.REVENUE) == pytest.approx(0.020220, abs=1e-6)

    def test_yoy_prior_period(self):
        # (383,285 - 394,328) / 394,328 = -0.028005
        assert t.yoy(self.REVENUE, offset=1) == pytest.approx(-0.028005, abs=1e-6)

    def test_growth_acceleration(self):
        # 0.020220 - (-0.028005) = 0.048225
        assert t.growth_acceleration(self.REVENUE) == pytest.approx(0.048225, abs=1e-6)

    def test_cagr_3y(self):
        # (391,035 / 365,817) ^ (1/3) - 1 = 0.022470
        assert t.cagr_over(self.REVENUE, 3) == pytest.approx(0.022470, abs=1e-6)

    def test_cagr_4y(self):
        # (391,035 / 274,515) ^ (1/4) - 1 = 0.092477
        assert t.cagr_over(self.REVENUE, 4) == pytest.approx(0.092477, abs=1e-6)

    def test_cagr_needs_enough_history(self):
        assert t.cagr_over(self.REVENUE[:2], 3) is None

    def test_incremental_operating_margin(self):
        profit = [("FY2024", 123_216.0), ("FY2023", 114_301.0)]
        # (123,216 - 114,301) / (391,035 - 383,285) = 8,915 / 7,750 = 1.150323
        assert t.incremental_margin(self.REVENUE, profit) == pytest.approx(1.150323, abs=1e-6)

    def test_incremental_margin_undefined_when_revenue_shrank(self):
        rev = [("FY2024", 380_000.0), ("FY2023", 391_035.0)]
        profit = [("FY2024", 100_000.0), ("FY2023", 123_216.0)]
        assert t.incremental_margin(rev, profit) is None

    def test_reinvestment_rate(self, fy24):
        # |−9,447| / 118,254 = 0.079887
        assert t.reinvestment_rate(fy24) == pytest.approx(0.079887, abs=1e-6)

    def test_rule_of_40(self):
        # 20% growth + 25% FCF margin = 45
        assert t.rule_of_40(0.20, 0.25) == pytest.approx(45.0)
        assert t.rule_of_40(None, 0.25) is None

    def test_derive_eps_prefers_the_reported_figure(self, fy24):
        assert t.derive_eps(fy24) == 6.08

    def test_derive_eps_falls_back_to_the_quotient(self):
        # 93,736 / 15,408.095 = 6.0835, close to the reported 6.08
        row = {"net_income": 93_736.0, "shares_diluted": 15_408.095}
        assert t.derive_eps(row) == pytest.approx(6.0835, abs=1e-3)

    def test_median(self):
        assert t.median([3.0, 1.0, 2.0]) == 2.0
        assert t.median([4.0, 1.0, 3.0, 2.0]) == 2.5
        assert t.median([None, None]) is None


class TestPercentileRank:
    def test_ranks_within_peers(self):
        # 3 of 4 peers sit below 20 -> 0.75
        assert t.percentile_rank(20.0, [5.0, 10.0, 15.0, 25.0]) == pytest.approx(0.75)

    def test_direction_inverts_for_lower_is_better(self):
        assert t.percentile_rank(20.0, [5.0, 10.0, 15.0, 25.0], higher_is_better=False) == pytest.approx(0.25)

    def test_requires_three_valid_peers(self):
        assert t.percentile_rank(20.0, [5.0, 10.0]) is None
        assert t.percentile_rank(20.0, [5.0, 10.0, None]) is None
        assert t.percentile_rank(20.0, [5.0, 10.0, 15.0]) is not None

    def test_ties_place_at_the_midpoint(self):
        assert t.percentile_rank(10.0, [10.0, 10.0, 10.0]) == pytest.approx(0.5)

    def test_none_value_ranks_nowhere(self):
        assert t.percentile_rank(None, [1.0, 2.0, 3.0]) is None
