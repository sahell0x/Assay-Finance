# ------------------------------------------------------------------------ primitives


class TestPrimitives:
    def test_safe_div_normal(self):
        assert r.safe_div(10.0, 4.0) == 2.5

    @pytest.mark.parametrize(
        "num,den", [(None, 4.0), (10.0, None), (10.0, 0.0), (None, None)]
    )
    def test_safe_div_returns_none_never_zero_or_inf(self, num, den):
        assert r.safe_div(num, den) is None

    def test_safe_div_can_reject_negative_denominators(self):
        assert r.safe_div(10.0, -5.0) == -2.0
        assert r.safe_div(10.0, -5.0, allow_negative_denom=False) is None

    def test_average_of_balances(self):
        assert r.average(100.0, 200.0) == 150.0
        assert r.average(100.0, None) == 100.0
        assert r.average(None, 200.0) == 200.0
        assert r.average(None, None) is None

    def test_pct_change_refuses_a_non_positive_base(self):
        assert r.pct_change(110.0, 100.0) == pytest.approx(0.10)
        assert r.pct_change(5.0, -10.0) is None
        assert r.pct_change(5.0, 0.0) is None

    def test_cagr(self):
        # 100 -> 121 over two years is exactly 10% a year.
        assert r.cagr(121.0, 100.0, 2.0) == pytest.approx(0.10, rel=1e-9)

    def test_cagr_refuses_negative_or_zero_endpoints(self):
        assert r.cagr(121.0, -100.0, 2.0) is None
        assert r.cagr(-121.0, 100.0, 2.0) is None
        assert r.cagr(121.0, 0.0, 2.0) is None
        assert r.cagr(121.0, 100.0, 0.0) is None


# --------------------------------------------------------------------- profitability


class TestProfitability:
    def test_gross_margin(self, fy24):
        # 180,683 / 391,035 = 0.462063
        assert r.gross_margin(fy24) == pytest.approx(0.462063, abs=1e-6)

    def test_operating_margin(self, fy24):
        # 123,216 / 391,035 = 0.315103
        assert r.operating_margin(fy24) == pytest.approx(0.315103, abs=1e-6)

    def test_net_margin(self, fy24):
        # 93,736 / 391,035 = 0.239712
        assert r.net_margin(fy24) == pytest.approx(0.239712, abs=1e-6)

    def test_ebitda_margin(self, fy24):
        # EBITDA falls back to EBIT + D&A = 123,216 + 11,445 = 134,661
        # 134,661 / 391,035 = 0.344370
        assert fy24["ebitda"] == 134_661.0
        assert r.ebitda_margin(fy24) == pytest.approx(0.344370, abs=1e-6)

    def test_fcf_margin(self, fy24):
        # FCF = 118,254 - |−9,447| = 108,807 ; / 391,035 = 0.278254
        assert fy24["fcf"] == 108_807.0
        assert r.fcf_margin(fy24) == pytest.approx(0.278254, abs=1e-6)

    def test_roe_uses_average_equity_not_ending_equity(self, fy24, fy23):
        # avg equity = (56,950 + 62,146) / 2 = 59,548
        # 93,736 / 59,548 = 1.574125
        assert r.roe(fy24, fy23) == pytest.approx(1.574125, abs=1e-6)
        # Ending-equity ROE would be 1.6460 — materially different, so the test bites.
        assert r.roe(fy24, fy23) != pytest.approx(93_736.0 / 56_950.0, abs=1e-3)

    def test_roa(self, fy24, fy23):
        # avg assets = (364,980 + 352,583) / 2 = 358,781.5
        # 93,736 / 358,781.5 = 0.261262
        assert r.roa(fy24, fy23) == pytest.approx(0.261262, abs=1e-6)

    def test_invested_capital(self, fy24):
        # 106,629 + 56,950 - 29,943 = 133,636
        assert r.invested_capital(fy24) == 133_636.0

    def test_roic(self, fy24, fy23):
        # NOPAT = 123,216 x (1 - 29,749/123,485) = 123,216 x 0.7590883 = 93,531.81
        # IC FY24 = 133,636 ; IC FY23 = 111,088 + 62,146 - 29,965 = 143,269
        # avg IC = 138,452.5 ; 93,531.81 / 138,452.5 = 0.675552
        assert fy24["nopat"] == pytest.approx(93_531.81, abs=0.5)
        assert r.roic(fy24, fy23) == pytest.approx(0.675552, abs=1e-5)

    def test_asset_turnover(self, fy24, fy23):
        # 391,035 / 358,781.5 = 1.089897
        assert r.asset_turnover(fy24, fy23) == pytest.approx(1.089897, abs=1e-6)

    def test_equity_multiplier(self, fy24, fy23):
        # 358,781.5 / 59,548 = 6.025081
        assert r.equity_multiplier(fy24, fy23) == pytest.approx(6.025081, abs=1e-6)

    def test_dupont_identity_reconciles(self, fy24, fy23):
        d = r.dupont(fy24, fy23)
        # 0.239712 x 1.089897 x 6.024762 = 1.574109, which is ROE computed directly.
        assert d["product"] == pytest.approx(d["roe_direct"], rel=1e-9)
        assert d["reconciles"] is True


